/** Only trusted, checked-in icon names and shapes are serialized; no user-supplied markup. */
export function iconMarkup(name) {
  const shapes=icons[name];
  if(!shapes)throw new Error("Unknown interface icon: "+name);
  return `<svg class="ui-icon" data-icon="${name}" width="18" height="18" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.6" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">${shapes.map(([tag,attributes])=>`<${tag} ${Object.entries(attributes).map(([key,value])=>`${key}="${value}"`).join(" ")}/>`).join("")}</svg>`;
}

export function updateButtonIcon(button,name) {
  const current=button.querySelector(".ui-icon");
  if(current?.getAttribute("data-icon")===name)return;
  if(current)current.outerHTML=iconMarkup(name);
  else button.insertAdjacentHTML("afterbegin",iconMarkup(name));
}
